using System.CodeDom.Compiler;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace BHO.SceneReference.Editor
{
    public static class SceneEnumAutoGenerated
    {
        private const string GeneratedFileName = "SceneEnumGenerated";

        public static void Save(string[] scenesNames)
        {
            string path = GetOutputPath();
            string content = Build(scenesNames);
            
            if (File.Exists(path) && File.ReadAllText(path) == content)
                return;

            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
        }

        private static string Build(string[] scenesNames)
        {
            StringBuilder sb = new();

            sb.AppendLine("// Copyright (c) 2026 Black Hole Odyssey");
            sb.AppendLine("// Licensed under the MIT License. See LICENSE file in the project root for full license information.");
            sb.AppendLine("// Auto-generated — do not edit manually");
            sb.AppendLine();
            sb.AppendLine("namespace BHO.SceneReference");
            sb.AppendLine("{");
            sb.AppendLine("    public enum Scenes");
            sb.AppendLine("    {");

            HashSet<string> used = new();
            for (int i = 0; i < scenesNames.Length; i++)
            {
                string identifier = Sanitize(scenesNames[i]);

                if (!used.Add(identifier))
                {
                    string unique;
                    int suffix = 2;
                    while (!used.Add(unique = $"{identifier}_{suffix}"))
                        suffix++;

                    Debug.LogWarning($"[SceneEnum] Nom de scène en double : \"{scenesNames[i]}\" renommé en \"{unique}\".");
                    identifier = unique;
                }

                sb.AppendLine($"        {identifier} = {i},");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string Sanitize(string name)
        {
            StringBuilder sb = new();
            foreach (char c in name)
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');

            string result = sb.ToString();

            if (result.Length == 0 || char.IsDigit(result[0]))
                result = "_" + result;
            
            using CodeDomProvider provider = CodeDomProvider.CreateProvider("C#");
            if (!provider.IsValidIdentifier(result))
                result = "_" + result;

            return result;
        }

        private static string GetOutputPath()
        {
            string existing = FindScriptPath(GeneratedFileName);
            if (existing != null)
                return existing;
            
            string self = FindScriptPath(nameof(SceneEnumAutoGenerated));
            string editorDir = Path.GetDirectoryName(self)!;
            string runtimeDir = Path.GetDirectoryName(editorDir)!;
            return Path.Combine(runtimeDir, GeneratedFileName + ".cs").Replace('\\', '/');
        }

        private static string FindScriptPath(string scriptName)
        {
            foreach (string guid in AssetDatabase.FindAssets(scriptName))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid);
                if (p.EndsWith(".cs") && Path.GetFileNameWithoutExtension(p) == scriptName)
                    return p;
            }
            return null;
        }
    }
}