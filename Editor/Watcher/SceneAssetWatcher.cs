using System.Collections.Generic;
using System.IO;
using UnityEditor;

namespace BHO.SceneReference.Editor
{
    [InitializeOnLoad]
    public class SceneAssetWatcher : AssetPostprocessor
    {
        static SceneAssetWatcher()
        {
            EditorBuildSettings.sceneListChanged += RequestRegenerate;
        }

        static void OnPostprocessAllAssets(
            string[] imported, string[] deleted,
            string[] moved, string[] movedFrom)
        {
            if (HasScene(imported) || HasScene(deleted) || HasScene(moved) || HasScene(movedFrom))
                RequestRegenerate();
        }

        static bool HasScene(string[] paths)
        {
            foreach (string p in paths)
                if (p.EndsWith(".unity")) return true;
            return false;
        }

        static void RequestRegenerate()
        {
            EditorApplication.delayCall -= Regenerate;
            EditorApplication.delayCall += Regenerate;
        }

        [MenuItem("Tools/BHO/Regenerate Scenes Enum")]
        static void Regenerate()
        {
            SceneRegistry.Reload();
            
            List<string> names = new List<string>();
            foreach (EditorBuildSettingsScene s in EditorBuildSettings.scenes)
            {
                if (s.enabled)
                {
                    names.Add(Path.GetFileNameWithoutExtension(s.path));
                }
            }

            SceneEnumAutoGenerated.Save(names.ToArray());
        }
    }
}